def domain_matches(url: str, domain: str) -> bool:
    hostname = urlparse(url).hostname
    if not hostname:
        return False
    if hostname == domain:
        return True
    if _IPV4_RE.match(hostname):
        return False
    if hostname.endswith('.' + domain):
        return True
    return False


def grade_source(url: str) -> tuple[int, str] | None:
    if any(domain_matches(url, d) for d in URL_BLACKLIST):
        return 0, 'Untrusted'
    for domains, tier, label in URL_TIER_TABLE:
        if any(domain_matches(url, d) for d in domains):
            return tier, label
    return None
